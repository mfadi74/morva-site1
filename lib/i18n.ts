const DICTS: Record<Lang, Dict> = { en, es, ar };

/** Translate a key for a given language, falling back to English then the key. */
export function translate(lang: Lang, key: string): string {
  return DICTS[lang]?.[key] ?? en[key] ?? key;
}

/** Hook: returns a `t()` bound to the current language + the language itself. */
export function useT(): { t: (key: string) => string; lang: Lang; rtl: boolean } {
  const lang = useAppStore((s) => s.language);
  return {
    t: (key: string) => translate(lang, key),
    lang,
    rtl: isRTL(lang),
  };
}
